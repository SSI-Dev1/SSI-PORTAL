// Generates a catalogue import migration from an .xlsx workbook using the same parser as the
// Admin import dialog (src/lib/catalogueImport.ts).
//
//   node scripts/catalogue-sql.ts <workbook.xlsx> <migration.sql> "<source label>" [--json out.json] [--after <previous migration>]
import { readFileSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { parseCatalogue, readWorkbook } from '../src/lib/catalogueImport.ts';

const [, , input, output, source, ...opts] = process.argv;
const opt = (k: string) => (opts.includes(k) ? opts[opts.indexOf(k) + 1] : undefined);
const jsonOut = opt('--json');
const after = opt('--after') ?? '0007_course_catalogue';
if (!input || !output || !source) {
  console.error('usage: node scripts/catalogue-sql.ts <workbook.xlsx> <migration.sql> "<source label>" [--json out.json] [--after <previous migration>]');
  process.exit(1);
}
const parsed = parseCatalogue(readWorkbook(new Uint8Array(readFileSync(input))), source);
const json = JSON.stringify(parsed.payload, null, 2);
if (jsonOut) writeFileSync(jsonOut, JSON.stringify(parsed, null, 2));
const name = basename(output, '.sql');
const sql = `-- ${name}.sql — run after ${after}.sql
-- (Supabase SQL Editor: Save this query as "${name}")
--
-- Course catalogue import from "${basename(input)}" (${source}).
-- Generated by scripts/catalogue-sql.ts with the same parser the Admin import uses.
-- Runs public.import_catalogue(): adds or updates universities, courses and intakes by name
-- and never deletes anything. Safe to run more than once. The result row is the summary.
--
-- Universities: ${parsed.payload.universities.length} · Courses: ${parsed.payload.courses.length} · Intakes: ${parsed.payload.courses.reduce((n, c) => n + c.intakes.length, 0)} · Blacklisted institutions: ${parsed.payload.blacklist.length}
${parsed.notes.map((n) => `-- Note: ${n}`).join('\n')}
${parsed.invalid.map((i) => `-- Not imported / incomplete: ${i.where} — ${i.reason}`).join('\n')}
select public.import_catalogue($catalogue$
${json}
$catalogue$::jsonb, true) as summary;
`;
writeFileSync(output, sql);
console.log(JSON.stringify({ universities: parsed.payload.universities.length, courses: parsed.payload.courses.length, intakes: parsed.payload.courses.reduce((n, c) => n + c.intakes.length, 0), blacklist: parsed.payload.blacklist.length, invalid: parsed.invalid, notes: parsed.notes }, null, 2));
