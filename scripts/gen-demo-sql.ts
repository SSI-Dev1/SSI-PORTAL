// Generates supabase/demo_data.sql from the fictional sample data in src/data/seed.ts.
// For presentations/staging only — never load demo data into the production database.
// Run: npm run demo:sql
import { writeFileSync } from 'node:fs';
import { createSeed } from '../src/data/seed';

const db = createSeed();
const q = (v: unknown): string => {
  if (v === null || v === undefined || v === '') return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v) && v.every((x) => typeof x === 'string')) return `ARRAY[${v.map(q).join(',')}]::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table: string, rows: Record<string, unknown>[]) =>
  rows.length
    ? `insert into public.${table} (${Object.keys(rows[0]).join(', ')}) values\n${rows
        .map((r) => `  (${Object.values(r).map(q).join(', ')})`)
        .join(',\n')}\non conflict do nothing;\n`
    : '';

const out = [
  '-- DEMO DATA (fictional). For presentations / staging projects only.',
  '-- Do NOT run this against the production database. Generated by scripts/gen-demo-sql.ts.',
  'begin;',
  insert('universities', db.universities.map((u) => ({ id: u.id, name: u.name, country: u.country, city: u.city, ranking: u.ranking, type: u.type, partner_since: u.partnerSince, website: u.website }))),
  insert('courses', db.courses.map((c) => ({ id: c.id, university_id: c.universityId, name: c.name, level: c.level, field: c.field, duration: c.duration, tuition: c.tuition, currency: c.currency, intakes: c.intakes, ielts_min: c.ieltsMin }))),
  insert('students', db.students.map((s) => ({ id: s.id, partner_id: s.partnerId, first_name: s.firstName, last_name: s.lastName, email: s.email, phone: s.phone, dob: s.dob, gender: s.gender, nationality: s.nationality, passport_no: s.passportNo, address: s.address, qualification: s.qualification, institution: s.institution, gpa: s.gpa, graduation_year: s.graduationYear, english_test: s.englishTest, english_score: s.englishScore, preferred_countries: s.preferredCountries, preferred_level: s.preferredLevel, preferred_intake: s.preferredIntake, budget: s.budget, status: s.status, created_at: s.createdAt }))),
  insert('applications', db.applications.map((a) => ({ id: a.id, ref: a.ref, student_id: a.studentId, partner_id: a.partnerId, university_id: a.universityId, course_id: a.courseId, intake: a.intake, status: a.status, checklist: a.checklist }))),
  insert('assessments', db.assessments.map((a) => ({ id: a.id, student_id: a.studentId, partner_id: a.partnerId, course_id: a.courseId, status: a.status, notes: a.notes, requested_at: a.requestedAt }))),
  insert('payments', db.payments.map((p) => ({ id: p.id, invoice_no: p.invoiceNo, partner_id: p.partnerId, student_id: p.studentId ?? null, type: p.type, description: p.description, amount: p.amount, paid: p.paid, due_date: p.dueDate, status: p.status }))),
  insert('announcements', db.announcements.map((a) => ({ id: a.id, title: a.title, category: a.category, priority: a.priority, body: a.body, published: a.published, publish_at: a.publishAt, expires_at: a.expiresAt, audience: a.audience === 'all' ? null : a.audience, created_at: a.createdAt }))),
  insert('tasks', db.tasks.map((t) => ({ id: t.id, title: t.title, due: t.due, priority: t.priority, done: t.done, assignee: t.assignee, related: t.related ?? null }))),
  '-- Documents are not included: upload real files through the app (they go to private storage).',
  'commit;',
].join('\n');

writeFileSync('supabase/demo_data.sql', out); // run from the project root (npm run demo:sql)
console.log('wrote supabase/demo_data.sql');
